import streamlit as st
from google import genai
from google.genai import types


# ==========================================
# 1. НАСТРОЙКИ СТРАНИЦЫ
# ==========================================

st.set_page_config(
    page_title="ОРТ AI — ИИ-репетитор",
    page_icon="🎓",
    layout="centered"
)

st.title("🎓 ОРТ AI")
st.caption("Твой ИИ-репетитор для подготовки к ОРТ в Кыргызстане")


# ==========================================
# 2. ИНСТРУКЦИЯ ИИ-РЕПЕТИТОРА
# ==========================================

SYSTEM_PROMPT = """
Ты — ОРТ AI, опытный виртуальный репетитор для подготовки
к Общереспубликанскому тестированию (ОРТ) в Кыргызстане.

Твоя главная цель — научить ученика самостоятельно решать
задачи, понимать материал и эффективно готовиться к экзамену.

ЯЗЫК:
- По умолчанию отвечай на русском языке.
- Если ученик пишет на кыргызском языке, отвечай на кыргызском.
- Если ученик просит другой язык, переключись на него.
- Объясняй простыми словами, подходящими школьнику.

ПРИНЦИПЫ ОБУЧЕНИЯ:

1. Не ограничивайся выдачей ответа.
2. Объясняй ход решения по шагам.
3. Показывай формулы и объясняй значение переменных.
4. Приводи понятные примеры.
5. Проверяй вычисления перед отправкой ответа.
6. Если задача сформулирована неоднозначно, уточняй условие.
7. Не придумывай условия официального экзамена, даты,
   проходные баллы и правила поступления.
8. Если не уверен в актуальных официальных сведениях,
   прямо сообщай об этом.
9. Не утверждай, что сгенерированные задания являются
   официальными заданиями ОРТ.
10. Поддерживай ученика, но не хвали автоматически каждый ответ.

РАЗДЕЛЫ ПОДГОТОВКИ:

- Математика и количественные задачи.
- Аналогии и логические связи.
- Чтение и понимание текста.
- Грамотность и работа с языком.
- Логическое мышление.
- Стратегии решения тестовых заданий.

АЛГОРИТМ РЕШЕНИЯ ЗАДАЧИ:

1. Кратко объясни, что требуется найти.
2. Определи, какие данные известны.
3. Выбери подходящий способ решения.
4. Реши задачу по шагам.
5. Проверь результат.
6. Назови правильный ответ.
7. Предложи похожее задание для самостоятельной тренировки.

РЕЖИМЫ РАБОТЫ:

Если ученик выбрал режим «Обучение»:
Объясняй тему подробно, начиная с основ.

Если выбран режим «Практика»:
Предлагай задания, позволяй ученику сначала подумать
и затем объясняй решение.

Если выбран режим «Проверка знаний»:
Задавай вопросы по одному.
Не раскрывай правильный ответ до ответа ученика.
После ответа объясняй ошибки.

Если выбран режим «Разбор ошибки»:
Найди конкретную ошибку ученика, объясни её причину
и покажи, как рассуждать правильно.

Если ученик прислал только ответ:
Попроси его объяснить ход решения, когда это поможет
выявить пробелы в понимании.

ВАЖНО:
Будь терпеливым, честным и последовательным.
Не выдумывай информацию.
Не выдавай предположение за установленный факт.
"""


# ==========================================
# 3. ПОЛУЧЕНИЕ API-КЛЮЧА
# ==========================================

try:
    api_key = st.secrets["GEMINI_API_KEY"]
except (KeyError, FileNotFoundError):
    st.error(
        "API-ключ не найден. Добавь GEMINI_API_KEY "
        "в настройки Secrets."
    )
    st.stop()

if not api_key:
    st.error("API-ключ пустой. Проверь настройки Secrets.")
    st.stop()


# ==========================================
# 4. СОЗДАНИЕ КЛИЕНТА
# ==========================================

try:
    client = genai.Client(api_key=api_key)
except Exception:
    st.error("Не удалось создать клиент Google GenAI.")
    st.stop()


# ==========================================
# 5. ВЫБОР РЕЖИМА ОБУЧЕНИЯ
# ==========================================

with st.sidebar:
    st.header("📚 Подготовка")

    mode = st.selectbox(
        "Выбери режим",
        [
            "Обучение",
            "Практика",
            "Проверка знаний",
            "Разбор ошибки"
        ]
    )

    subject = st.selectbox(
        "Выбери раздел",
        [
            "Все разделы",
            "Математика",
            "Аналогии",
            "Чтение и понимание текста",
            "Грамотность",
            "Логика"
        ]
    )

    st.divider()

    st.info(
        "Совет: проси объяснять не только правильный ответ, "
        "но и причины, по которым другие варианты неверны."
    )

    if st.button("🗑️ Очистить историю", use_container_width=True):
        st.session_state.messages = []
        st.rerun()


# ==========================================
# 6. ИСТОРИЯ ДИАЛОГА
# ==========================================

if "messages" not in st.session_state:
    st.session_state.messages = []

# Показываем предыдущие сообщения
for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])


# ==========================================
# 7. СПИСОК МОДЕЛЕЙ
# ==========================================

MODELS = [
    "gemini-3.8-flash",
    "gemini-2.5-flash"
]


# ==========================================
# 8. ФУНКЦИЯ ГЕНЕРАЦИИ ОТВЕТА
# ==========================================

def generate_answer(user_text, mode, subject):
    """
    Пробует модели по очереди.
    Если генерация одной модели завершается ошибкой,
    пробует следующую.
    """

    mode_instructions = {
        "Обучение": (
            "Подробно объясняй материал и показывай "
            "решение по шагам."
        ),
        "Практика": (
            "Помогай тренироваться. По возможности сначала "
            "предложи ученику попробовать решить задачу."
        ),
        "Проверка знаний": (
            "Задавай вопросы по одному. Не показывай ответ "
            "до попытки ученика."
        ),
        "Разбор ошибки": (
            "Внимательно анализируй решение ученика, "
            "находи ошибки и объясняй, как их исправить."
        )
    }

    context = f"""
    Текущий режим: {mode}.
    Раздел: {subject}.

    Дополнительные инструкции:
    {mode_instructions[mode]}
    """

    # Формируем контекст разговора
    conversation = [
        types.Content(
            role="user",
            parts=[
                types.Part(
                    text=(
                        "Инструкции текущего режима:\n"
                        + context
                    )
                )
            ]
        )
    ]

    for message in st.session_state.messages[-12:]:
        conversation.append(
            types.Content(
                role=message["role"],
                parts=[
                    types.Part(text=message["content"])
                ]
            )
        )

    conversation.append(
        types.Content(
            role="user",
            parts=[types.Part(text=user_text)]
        )
    )

    errors = []

    for model_name in MODELS:
        try:
            response = client.models.generate_content_stream(
                model=model_name,
                contents=conversation,
                config=types.GenerateContentConfig(
                    system_instruction=SYSTEM_PROMPT,
                    temperature=0.4,
                    max_output_tokens=4096
                )
            )

            # Важно: ошибка может появиться во время чтения
            # потока, поэтому обрабатываем её внутри try.
            chunks = []

            for chunk in response:
                if chunk.text:
                    chunks.append(chunk.text)
                    yield chunk.text

            if chunks:
                return

            errors.append(
                f"{model_name}: модель вернула пустой ответ."
            )

        except Exception as error:
            errors.append(
                f"{model_name}: {type(error).__name__}"
            )

    # Если ни одна модель не сработала
    yield (
        "\n\nНе удалось получить ответ от доступных моделей. "
        "Проверь подключение к интернету, API-ключ, "
        "доступность моделей и ограничения API."
    )


# ==========================================
# 9. ПОЛЕ ВВОДА
# ==========================================

user_input = st.chat_input(
    "Напиши вопрос или задачу по ОРТ..."
)


# ==========================================
# 10. ОБРАБОТКА СООБЩЕНИЯ
# ==========================================

if user_input:

    # Сохраняем вопрос ученика
    st.session_state.messages.append(
        {
            "role": "user",
            "content": user_input
        }
    )

    with st.chat_message("user"):
        st.markdown(user_input)

    with st.chat_message("assistant"):
        response_placeholder = st.empty()

        answer_parts = []

        try:
            stream = generate_answer(
                user_text=user_input,
                mode=mode,
                subject=subject
            )

            for part in stream:
                answer_parts.append(part)
                response_placeholder.markdown(
                    "".join(answer_parts)
                )

            final_answer = "".join(answer_parts)

        except Exception:
            final_answer = (
                "Произошла ошибка при обработке запроса. "
                "Попробуй ещё раз через некоторое время."
            )

            response_placeholder.error(final_answer)

        # Сохраняем ответ
        st.session_state.messages.append(
            {
                "role": "assistant",
                "content": final_answer
            }
        )
